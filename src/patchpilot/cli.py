def main() -> None:
    """PatchPilot CLI."""


@app.command(name="version")
def version_cmd() -> None:
    """Show the PatchPilot version."""
    console.print(f"[bold cyan]PatchPilot[/bold cyan] version [green]{__version__}[/green]")


@app.command(name="init")
def init_cmd(
    path: Path | None = typer.Option(
        None,
        "--path",
        "-p",
        help="Path where configuration file should be written (defaults to .patchpilot.toml)",
    ),
    force: bool = typer.Option(
        False,
        "--force",
        "-f",
        help="Overwrite existing configuration file if present",
    ),
) -> None:
    """Create a default .patchpilot.toml configuration file."""
    target_path = path or Path(".patchpilot.toml")
    if target_path.is_file() and not force:
        console.print(
            f"[bold yellow]Configuration file already exists at '{target_path}'.[/bold yellow]\n"
            "Pass '--force' to overwrite the existing configuration."
        )
        raise typer.Exit(code=1)

    if target_path.parent and not target_path.parent.exists():
        target_path.parent.mkdir(parents=True, exist_ok=True)

    target_path.write_text(DEFAULT_CONFIG_TEMPLATE, encoding="utf-8")

    # Validate configuration parses cleanly
    try:
        PatchPilotConfig.load(target_path)
    except Exception as e:
        console.print(f"[bold red]Generated configuration failed validation:[/bold red] {e}")
        raise typer.Exit(code=1) from None

    console.print(
        f"[bold green][OK] Initialized configuration at:[/bold green] {target_path.resolve()}\n"
        "Next step: Run [bold cyan]patchpilot doctor[/bold cyan] to verify environment readiness."
    )


@app.command(name="doctor")
def doctor_cmd(
    config_file: Path | None = typer.Option(
        None, "--config", "-c", help="Path to custom .toml configuration file"
    ),
    probe_tools: bool = typer.Option(
        False, "--probe-tools", help="Send a test prompt to probe model native tool-calling"
    ),
) -> None:
    """Check system health, dependencies, Ollama connectivity, and sandbox readiness."""
    console.print(
        Panel.fit("[bold blue]PatchPilot System Diagnostics[/bold blue]", border_style="blue")
    )
    table = Table(title="Diagnostic Checks", show_header=True, header_style="bold magenta")
    table.add_column("Component", style="dim", width=24)
    table.add_column("Status", width=14)
    table.add_column("Details")

    remediations: list[str] = []

    # 1. Python version
    py_ver = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
    py_ok = sys.version_info >= (3, 11)
    table.add_row(
        "Python Runtime",
        "[green]PASS[/green]" if py_ok else "[red]FAIL[/red]",
        f"Python {py_ver} ({sys.executable})",
    )
    if not py_ok:
        remediations.append("Python 3.11+ is required. Please install Python 3.11, 3.12, or 3.13.")

    # 2. Config loading
    cfg: PatchPilotConfig | None = None
    cfg_ok = False
    try:
        cfg = PatchPilotConfig.load(config_file)
        cfg_ok = True
        table.add_row(
            "Configuration",
            "[green]PASS[/green]",
            f"Model: {cfg.model_name} | Endpoint: {cfg.ollama_base_url}",
        )
    except Exception as e:
        table.add_row("Configuration", "[red]FAIL[/red]", str(e))
        remediations.append(
            f"Configuration error: {e}. Run 'patchpilot init' to create a clean configuration."
        )

    # 3. Ollama connectivity
    ollama_ok = False
    model_ok = False
    client: OllamaClient | None = None
    if cfg is not None:
        client = OllamaClient(cfg)
        ollama_ok = client.is_reachable()
        table.add_row(
            "Ollama Server",
            "[green]ONLINE[/green]" if ollama_ok else "[yellow]UNAVAILABLE[/yellow]",
            f"Endpoint: {cfg.ollama_base_url}"
            if ollama_ok
            else f"Cannot reach {cfg.ollama_base_url}. Ensure Ollama is running.",
        )
        if not ollama_ok:
            remediations.append(
                f"Ollama server is offline. Ensure Ollama is running at {cfg.ollama_base_url} ('ollama serve' or launch Ollama Desktop)."
            )

        # 4. Target Model Installed
        if ollama_ok:
            try:
                model_ok = client.is_model_installed(cfg.model_name)
                table.add_row(
                    "Model Availability",
                    "[green]INSTALLED[/green]" if model_ok else "[yellow]MISSING[/yellow]",
                    f"Model '{cfg.model_name}' is available"
                    if model_ok
                    else f"Model '{cfg.model_name}' not installed. Run: ollama pull {cfg.model_name}",
                )
                if not model_ok:
                    remediations.append(
                        f"Model '{cfg.model_name}' not installed. Run: ollama pull {cfg.model_name}"
                    )
            except Exception as e:
                table.add_row("Model Availability", "[red]ERROR[/red]", str(e))
                remediations.append(f"Error checking model availability: {e}")
        else:
            table.add_row("Model Availability", "[dim]SKIPPED[/dim]", "Ollama is offline")
            remediations.append(
                f"After starting Ollama, verify model is installed: ollama pull {cfg.model_name}"
            )
    else:
        table.add_row("Ollama Server", "[dim]SKIPPED[/dim]", "Configuration invalid")
        table.add_row("Model Availability", "[dim]SKIPPED[/dim]", "Configuration invalid")

    # 5. Tool-calling capability probe (optional)
    probe_ok = True
    if probe_tools:
        if ollama_ok and model_ok and client is not None:
            with console.status("Probing model tool-calling capability..."):
                cap_ok, cap_msg = client.check_tool_capability()
                probe_ok = cap_ok
                table.add_row(
                    "Tool-Calling Probe",
                    "[green]SUPPORTED[/green]" if cap_ok else "[yellow]LIMITED[/yellow]",
                    cap_msg,
                )
                if not cap_ok:
                    remediations.append(f"Tool-calling probe reported limitations: {cap_msg}")
        else:
            table.add_row("Tool-Calling Probe", "[dim]SKIPPED[/dim]", "Requires Ollama and model")
            probe_ok = False
            remediations.append("Cannot probe tool-calling because Ollama or model is unavailable.")

    # 6. Docker Sandbox
    effective_cfg = cfg or PatchPilotConfig()
    runner = TestRunner(effective_cfg)
    docker_ok = runner.is_docker_available()
    table.add_row(
        "Docker CLI / Daemon",
        "[green]AVAILABLE[/green]" if docker_ok else "[yellow]UNAVAILABLE[/yellow]",
        "Docker daemon reachable"
        if docker_ok
        else "Docker not running. Sandboxed testing unavailable.",
    )
    if not docker_ok:
        remediations.append("Start Docker Desktop and verify daemon status with: docker info")

    image_ok = runner.is_sandbox_image_available() if docker_ok else False
    table.add_row(
        "Sandbox Image",
        "[green]READY[/green]" if image_ok else "[yellow]NOT BUILT[/yellow]",
        f"Image '{runner.docker_image}' found"
        if image_ok
        else f"Build with: docker build -t {runner.docker_image} sandbox/",
    )
    if docker_ok and not image_ok:
        remediations.append(
            f"Build sandbox image from repository root: docker build -t {runner.docker_image} .\\sandbox\\"
        )
    elif not docker_ok:
        remediations.append(
            f"After starting Docker, build sandbox image: docker build -t {runner.docker_image} .\\sandbox\\"
        )

    # 7. Data Storage Directory
    data_dir_ok = False
    try:
        effective_cfg.data_dir.mkdir(parents=True, exist_ok=True)
        test_file = effective_cfg.data_dir / ".write_test"
        test_file.write_text("ok", encoding="utf-8")
        test_file.unlink()
        data_dir_ok = True
        table.add_row(
            "Data Directory", "[green]WRITABLE[/green]", str(effective_cfg.data_dir.resolve())
        )
    except Exception as e:
        table.add_row(
            "Data Directory", "[red]FAIL[/red]", f"Cannot write to {effective_cfg.data_dir}: {e}"
        )
        remediations.append(f"Data directory '{effective_cfg.data_dir}' is not writable: {e}")

    console.print(table)

    is_ready = (
        py_ok
        and cfg_ok
        and ollama_ok
        and model_ok
        and docker_ok
        and image_ok
        and data_dir_ok
        and probe_ok
    )

    if is_ready:
        console.print(
            Panel.fit(
                "[bold green]System Status: READY[/bold green]\n"
                "Environment is fully ready for safe sandboxed repairs.\n\n"
                "[bold]Next steps:[/bold]\n"
                "  - Run the demo: [bold cyan]patchpilot demo[/bold cyan]\n"
                '  - Repair a project: [bold cyan]patchpilot repair --repo <path> --task "<description>"[/bold cyan]',
                border_style="green",
            )
        )
    else:
        rem_lines = "\n".join(f"  [yellow]-[/yellow] {r}" for r in remediations)
        console.print(
            Panel.fit(
                "[bold red]System Status: NOT READY[/bold red]\n"
                "The environment is missing dependencies required for safe sandboxed repairs.\n\n"
                "[bold]Action Items:[/bold]\n"
                f"{rem_lines}",
                border_style="red",
            )
        )
        raise typer.Exit(code=1)


@app.command(name="models")
def models_cmd(
    config_file: Path | None = typer.Option(None, "--config", "-c", help="Config file path"),
) -> None:
    """List installed models in local Ollama."""
    cfg = PatchPilotConfig.load(config_file)
    client = OllamaClient(cfg)
    if not client.is_reachable():
        console.print(f"[red]Error:[/red] Ollama is not running at {cfg.ollama_base_url}")
        raise typer.Exit(code=1)

    try:
        models = client.list_models()
        table = Table(title="Installed Ollama Models", show_header=True)
        table.add_column("Model Name", style="bold cyan")
        table.add_column("Status")

        for m in sorted(models):
            is_target = m == cfg.model_name or m.split(":")[0] == cfg.model_name.split(":")[0]
            status_text = "[green]Configured Model[/green]" if is_target else "[dim]Available[/dim]"
            table.add_row(m, status_text)

        console.print(table)
    except Exception as e:
        console.print(f"[red]Failed to query models:[/red] {e}")
        raise typer.Exit(code=1) from None


@app.command(name="chat")
def chat_cmd(
    prompt: str = typer.Argument(..., help="Prompt string to send to local model"),
    config_file: Path | None = typer.Option(None, "--config", "-c", help="Config file path"),
) -> None:
    """Perform direct diagnostic request to the configured local model."""
    cfg = PatchPilotConfig.load(config_file)
    client = OllamaClient(cfg)
    with console.status(f"Querying {cfg.model_name}..."):
        try:
            resp = client.chat(messages=[{"role": "user", "content": prompt}])
            content = resp.get("message", {}).get("content", "")
            console.print(Panel(content, title=f"Model: {cfg.model_name}", border_style="cyan"))
        except Exception as e:
            console.print(f"[red]Chat request failed:[/red] {e}")
            raise typer.Exit(code=1) from None


@app.command(name="demo")
def demo_cmd(
    repo: Path | None = typer.Option(
        None,
        "--repo",
        "-r",
        help="Path to demo repository (defaults to bundled buggy calculator project)",
    ),
    config_file: Path | None = typer.Option(None, "--config", "-c", help="Config file path"),
) -> None:
    """Demonstrate the built-in calculator repair safely in an isolated sandbox."""
    console.print(
        Panel.fit(
            "[bold cyan]PatchPilot Safe Demo[/bold cyan]\n"
            "Demonstrating isolated self-healing repair on buggy calculator project.",
            border_style="cyan",
        )
    )

    # 1. Locate demo repository
    demo_repo: Path | None = None
    if repo is not None:
        if repo.is_dir():
            demo_repo = repo.resolve()
        else:
            console.print(
                f"[bold red]Error:[/bold red] Specified demo repository '{repo}' does not exist."
            )
            raise typer.Exit(code=1)
    else:
        candidate_paths = [
            Path("examples/buggy_python_project"),
            Path(__file__).resolve().parent.parent.parent / "examples" / "buggy_python_project",
        ]
        for candidate in candidate_paths:
            if candidate.is_dir() and (candidate / "calculator.py").is_file():
                demo_repo = candidate.resolve()
                break

    if demo_repo is None:
        console.print(
            "[bold red]Error:[/bold red] Bundled demo project 'examples/buggy_python_project' not found.\n"
            "Please specify a repository with: [bold cyan]patchpilot demo --repo <path>[/bold cyan]\n"
            'Or run repair directly: [bold cyan]patchpilot repair --repo <path> --task "<description>"[/bold cyan]'
        )
        raise typer.Exit(code=1)

    # 2. Load configuration — demo never enables host execution implicitly
    try:
        cfg = PatchPilotConfig.load(config_file)
    except Exception as e:
        console.print(f"[bold red]Configuration error:[/bold red] {e}")
        raise typer.Exit(code=1) from None

    cfg.allow_host_execution = False

    # 3. Preflight Check: Ollama server
    client = OllamaClient(cfg)
    if not client.is_reachable():
        console.print(
            f"[bold red]Error:[/bold red] Ollama server is unreachable at {cfg.ollama_base_url}.\n"
            "Ensure Ollama is running ('ollama serve' or launch Ollama Desktop).\n"
            "Run [bold cyan]patchpilot doctor[/bold cyan] to verify system health."
        )
        raise typer.Exit(code=1)

    # 4. Preflight Check: Configured model
    try:
        model_installed = client.is_model_installed(cfg.model_name)
    except Exception as e:
        console.print(f"[bold red]Error checking model:[/bold red] {e}")
        raise typer.Exit(code=1) from None

    if not model_installed:
        console.print(
            f"[bold red]Error:[/bold red] Model '{cfg.model_name}' is not installed in local Ollama.\n"
            f"Run: [bold cyan]ollama pull {cfg.model_name}[/bold cyan]"
        )
        raise typer.Exit(code=1)

    # 5. Preflight Check: Docker and sandbox image (mandatory for demo)
    runner = TestRunner(cfg)
    if not runner.is_docker_available():
        console.print(
            "[bold red]Error:[/bold red] Docker daemon is not running or unreachable.\n"
            "The PatchPilot demo requires Docker for safe isolated test execution.\n\n"
            "[bold]To resolve this, run from repository root:[/bold]\n"
            "  [cyan]docker info[/cyan]\n"
            f"  [cyan]docker build -t {runner.docker_image} .\\sandbox\\ [/cyan]\n"
            "  [cyan]patchpilot doctor[/cyan]"
        )
        raise typer.Exit(code=1)

    if not runner.is_sandbox_image_available():
        console.print(
            f"[bold red]Error:[/bold red] Docker sandbox image '{runner.docker_image}' is not built.\n"
            "The PatchPilot demo requires the sandbox image for safe isolated test execution.\n\n"
            "[bold]To resolve this, run from repository root:[/bold]\n"
            f"  [cyan]docker build -t {runner.docker_image} .\\sandbox\\ [/cyan]\n"
            "  [cyan]patchpilot doctor[/cyan]"
        )
        raise typer.Exit(code=1)

    # 6. Execute demo repair mission
    task_desc = "Fix the bug in the calculator's add function. Preserve the public API and ensure all tests pass."
    task_request = TaskRequest(
        repo_path=str(demo_repo),
        task_description=task_desc,
        test_suite=TestSuiteName.PYTEST,
        test_target="tests/test_calculator.py",
    )

    console.print(
        Panel(
            f"[bold]Target Repository:[/bold] {demo_repo}\n"
            f"[bold]Task:[/bold] {task_desc}\n"
            f"[bold]Test Suite:[/bold] pytest (tests/test_calculator.py)\n"
            f"[bold]Model:[/bold] {cfg.model_name}\n"
            f"[bold]Safety:[/bold] Isolated Docker sandbox (original repository immutable)",
            title="[bold green]Executing Demo Repair[/bold green]",
            border_style="green",
        )
    )

    orchestrator = AgentOrchestrator(cfg, ollama_client=client, test_runner=runner)

    with console.status("[bold green]Executing isolated repair workflow...[/bold green]"):
        try:
            report = orchestrator.run_repair(task_request)
        except Exception as e:
            console.print(f"[bold red]Demo repair failed with exception:[/bold red] {e}")
            raise typer.Exit(code=1) from None

    # Report run ID and artifact storage
    run_store = RunStore(cfg.data_dir)
    report_path = run_store.runs_dir / f"{report.run_id}.json"
    patch_path = run_store.runs_dir / f"{report.run_id}.patch"

    status_style = {
        RepairStatus.FIXED: "bold green",
        RepairStatus.PARTIALLY_FIXED: "bold yellow",
        RepairStatus.UNRESOLVED: "bold red",
        RepairStatus.FAILED_SAFETY_CHECK: "bold red reverse",
        RepairStatus.CANCELLED: "dim",
    }.get(report.status, "white")

    console.print(f"\n[bold]Run ID:[/bold] {report.run_id}")
    console.print(
        f"[bold]Final Status:[/bold] [{status_style}]{report.status.value}[/{status_style}]"
    )
    console.print(
        f"[bold]Duration:[/bold] {report.duration_seconds:.2f}s | [bold]Attempts:[/bold] {report.attempts_made}/{report.max_attempts}"
    )
    console.print(
        f"[bold]Original Repository Untouched:[/bold] [{'green' if report.original_repo_unmodified else 'red'}]{report.original_repo_unmodified}[/]"
    )
    console.print(f"[bold]Report Artifact:[/bold] {report_path.resolve()}")
    if patch_path.is_file():
        console.print(f"[bold]Patch Artifact:[/bold] {patch_path.resolve()}")

    if report.patch and report.patch.unified_diff:
        console.print("\n[bold]Generated Unified Diff:[/bold]")
        console.print(Syntax(report.patch.unified_diff, "diff", theme="monokai", line_numbers=True))

    if report.status == RepairStatus.FIXED:
        console.print(
            "\n[bold green][SUCCESS] Demo repair successfully verified against tests without regressions![/bold green]"
        )
    else:
        console.print(
            f"\n[yellow]Demo repair concluded with status: {report.status.value}[/yellow]"
        )
        if report.error_message:
            console.print(f"[red]Failure Reason:[/red] {report.error_message}")
        raise typer.Exit(code=1)


@app.command(name="repair")
def repair_cmd(
    repo: Path = typer.Option(..., "--repo", "-r", help="Path to target source repository"),
    task: str = typer.Option(..., "--task", "-t", help="Description of the bug to resolve"),
    suite: TestSuiteName = typer.Option(
        TestSuiteName.PYTEST, "--test-suite", "-s", help="Predefined test suite to execute"
    ),
    target: str | None = typer.Option(
        None, "--test-target", help="Optional targeted test file or directory"
    ),
    allow_host_execution: bool = typer.Option(
        False, "--allow-host-execution", help="Unsafely execute tests on the host without Docker"
    ),
    config_file: Path | None = typer.Option(None, "--config", "-c", help="Config file path"),
) -> None:
    """Execute isolated self-healing repair pipeline on a repository."""
    # Preflight Check 1: Target repo exists
    repo_resolved = repo.resolve()
    if not repo.exists() or not repo.is_dir():
        console.print(
            f"[bold red]Error:[/bold red] Target repository '{repo_resolved}' does not exist or is not a directory."
        )
        raise typer.Exit(code=1)

    # Preflight Check 2: Load and validate configuration
    try:
        cfg = PatchPilotConfig.load(config_file)
    except Exception as e:
        console.print(f"[bold red]Configuration error:[/bold red] {e}")
        raise typer.Exit(code=1) from None

    if allow_host_execution:
        cfg.allow_host_execution = True
        console.print("[yellow bold]WARNING: Unsafe host execution mode enabled.[/yellow bold]")

    # Preflight Check 3: Ollama connectivity
    client = OllamaClient(cfg)
    if not client.is_reachable():
        console.print(
            f"[bold red]Error:[/bold red] Ollama server is unreachable at {cfg.ollama_base_url}.\n"
            "Ensure Ollama is running ('ollama serve' or open Ollama Desktop).\n"
            "Run [bold cyan]patchpilot doctor[/bold cyan] to verify system health."
        )
        raise typer.Exit(code=1)

    # Preflight Check 4: Model installed
    try:
        model_installed = client.is_model_installed(cfg.model_name)
    except Exception as e:
        console.print(f"[bold red]Error checking model:[/bold red] {e}")
        raise typer.Exit(code=1) from None

    if not model_installed:
        console.print(
            f"[bold red]Error:[/bold red] Model '{cfg.model_name}' is not installed in local Ollama.\n"
            f"Run: [bold cyan]ollama pull {cfg.model_name}[/bold cyan]"
        )
        raise typer.Exit(code=1)

    # Preflight Check 5: Docker sandbox (unless explicit unsafe host execution requested)
    runner = TestRunner(cfg)
    if not cfg.allow_host_execution:
        if not runner.is_docker_available():
            console.print(
                "[bold red]Error:[/bold red] Docker daemon is not running or unreachable."
            )
            console.print("PatchPilot requires Docker for safe isolated test execution.\n")
            console.print("[bold]To resolve this, run from repository root:[/bold]")
            console.print("  [cyan]docker info[/cyan]")
            console.print(f"  [cyan]docker build -t {runner.docker_image} .\\sandbox\\ [/cyan]")
            console.print("  [cyan]patchpilot doctor[/cyan]\n")
            console.print(
                "[dim]Or pass --allow-host-execution to unsafely run tests directly on the host.[/dim]"
            )
            raise typer.Exit(code=1)

        if not runner.is_sandbox_image_available():
            console.print(
                f"[bold red]Error:[/bold red] Docker sandbox image '{runner.docker_image}' is not built."
            )
            console.print(
                "PatchPilot requires the sandbox image for safe isolated test execution.\n"
            )
            console.print("[bold]To resolve this, run from repository root:[/bold]")
            console.print(f"  [cyan]docker build -t {runner.docker_image} .\\sandbox\\ [/cyan]")
            console.print("  [cyan]patchpilot doctor[/cyan]\n")
            console.print(
                "[dim]Or pass --allow-host-execution to unsafely run tests directly on the host.[/dim]"
            )
            raise typer.Exit(code=1)

    task_request = TaskRequest(
        repo_path=str(repo_resolved),
        task_description=task,
        test_suite=suite,
        test_target=target,
    )

    console.print(
        Panel(
            f"[bold]Target Repository:[/bold] {repo_resolved}\n"
            f"[bold]Task:[/bold] {task}\n"
            f"[bold]Test Suite:[/bold] {suite.value}"
            + (f" ({target})" if target else "")
            + f"\n[bold]Model:[/bold] {cfg.model_name}\n"
            f"[bold]Safety:[/bold] Original repository will NOT be modified.",
            title="[bold green]PatchPilot Repair Mission[/bold green]",
            border_style="green",
        )
    )

    orchestrator = AgentOrchestrator(cfg, ollama_client=client, test_runner=runner)

    with console.status("[bold green]Executing isolated repair workflow...[/bold green]"):
        try:
            report = orchestrator.run_repair(task_request)
        except Exception as e:
            console.print(f"[bold red]Repair failed with exception:[/bold red] {e}")
            raise typer.Exit(code=1) from None

    # Display results
    status_style = {
        RepairStatus.FIXED: "bold green",
        RepairStatus.PARTIALLY_FIXED: "bold yellow",
        RepairStatus.UNRESOLVED: "bold red",
        RepairStatus.FAILED_SAFETY_CHECK: "bold red reverse",
        RepairStatus.CANCELLED: "dim",
    }.get(report.status, "white")

    run_store = RunStore(cfg.data_dir)
    report_path = run_store.runs_dir / f"{report.run_id}.json"
    patch_path = run_store.runs_dir / f"{report.run_id}.patch"

    console.print(f"\n[bold]Run ID:[/bold] {report.run_id}")
    console.print(
        f"[bold]Final Status:[/bold] [{status_style}]{report.status.value}[/{status_style}]"
    )
    console.print(
        f"[bold]Duration:[/bold] {report.duration_seconds:.2f}s | [bold]Attempts:[/bold] {report.attempts_made}/{report.max_attempts}"
    )
    console.print(
        f"[bold]Original Repository Untouched:[/bold] [{'green' if report.original_repo_unmodified else 'red'}]{report.original_repo_unmodified}[/]"
    )
    console.print(f"[bold]Report Artifact:[/bold] {report_path.resolve()}")
    if patch_path.is_file():
        console.print(f"[bold]Patch Artifact:[/bold] {patch_path.resolve()}")

    if report.patch and report.patch.unified_diff:
        console.print("\n[bold]Generated Unified Diff:[/bold]")
        console.print(Syntax(report.patch.unified_diff, "diff", theme="monokai", line_numbers=True))

    if report.status == RepairStatus.FIXED:
        console.print(
            "\n[bold green][SUCCESS] Patch successfully verified against test suite without regressions.[/bold green]"
        )
    elif report.status == RepairStatus.FAILED_SAFETY_CHECK:
        console.print("\n[bold red][FAILED] RUN FAILED SAFETY CHECKS.[/bold red]")
        for violation in report.safety_violations:
            console.print(f"  - [red]{violation}[/red]")
        raise typer.Exit(code=2)
    else:
        console.print(f"\n[yellow]Repair concluded with status: {report.status.value}[/yellow]")
        if report.error_message:
            console.print(f"[red]Failure Reason:[/red] {report.error_message}")
        raise typer.Exit(code=1)


@runs_app.command(name="list")
def runs_list_cmd(
    config_file: Path | None = typer.Option(None, "--config", "-c", help="Config file path"),
) -> None:
    """List recent repair runs."""
    cfg = PatchPilotConfig.load(config_file)
    store = RunStore(cfg.data_dir)
    runs = store.list_runs()

    if not runs:
        console.print("[dim]No repair runs recorded in data directory.[/dim]")
        return

    table = Table(title="PatchPilot Repair History", show_header=True)
    table.add_column("Run ID", style="bold cyan")
    table.add_column("Status")
    table.add_column("Duration")
    table.add_column("Attempts")
    table.add_column("Task")

    for r in runs:
        status_color = (
            "green" if r["status"] == "FIXED" else "red" if "FAIL" in r["status"] else "yellow"
        )
        table.add_row(
            r["run_id"],
            f"[{status_color}]{r['status']}[/{status_color}]",
            f"{r['duration_seconds']:.1f}s",
            str(r["attempts"]),
            r["task"],
        )
    console.print(table)


@runs_app.command(name="show")
def runs_show_cmd(
    run_id: str = typer.Argument(..., help="Run ID to inspect"),
    config_file: Path | None = typer.Option(None, "--config", "-c", help="Config file path"),
) -> None:
    """Display detailed report and diff for a specific run."""
    cfg = PatchPilotConfig.load(config_file)
    store = RunStore(cfg.data_dir)
    report = store.get_run(run_id)

    if not report:
        console.print(f"[red]Error:[/red] Run '{run_id}' not found.")
        raise typer.Exit(code=1)

    console.print(
        Panel(
            f"[bold]Run ID:[/bold] {report.run_id}\n[bold]Status:[/bold] {report.status.value}\n[bold]Duration:[/bold] {report.duration_seconds:.2f}s",
            title="Run Details",
            border_style="cyan",
        )
    )

    if report.patch and report.patch.unified_diff:
        console.print("\n[bold]Unified Diff:[/bold]")
        console.print(Syntax(report.patch.unified_diff, "diff", theme="monokai", line_numbers=True))
    else:
        console.print("[dim]No file modifications in this run.[/dim]")


@app.command(name="eval")
def eval_cmd(
    suite: str = typer.Option("smoke", "--suite", "-s", help="Benchmark suite to run (smoke)"),
    allow_host_execution: bool = typer.Option(
        False,
        "--allow-host-execution",
        help="Unsafely execute benchmark tests on the host without Docker",
    ),
    config_file: Path | None = typer.Option(None, "--config", "-c", help="Config file path"),
) -> None:
    """Run deterministic benchmark evaluation cases."""
    cfg = PatchPilotConfig.load(config_file)
    if allow_host_execution:
        cfg.allow_host_execution = True
        console.print(
            "[yellow bold]WARNING: Unsafe host execution mode enabled for benchmark evaluation.[/yellow bold]"
        )

    console.print(f"[bold cyan]Running PatchPilot benchmark suite:[/bold cyan] {suite}")

    with console.status("Evaluating benchmark cases..."):
        eval_report = run_smoke_benchmark(cfg)

    table = Table(title="Benchmark Results", show_header=True)
    table.add_column("Case ID", style="bold")
    table.add_column("Status")
    table.add_column("Duration")
    table.add_column("Attempts")
    table.add_column("Tools Called")

    for res in eval_report.results:
        color = "green" if res.success else "red"
        table.add_row(
            res.case_id,
            f"[{color}]{res.status.value}[/{color}]",
            f"{res.duration_seconds:.2f}s",
            str(res.attempts),
            str(res.tool_calls_count),
        )

    console.print(table)
    console.print(
        f"\n[bold]Summary:[/bold] {eval_report.passed_cases}/{eval_report.total_cases} passed "
        f"({eval_report.success_rate * 100:.1f}%) in {eval_report.total_duration_seconds:.2f}s"
    )

    if eval_report.failed_cases > 0:
        raise typer.Exit(code=1)


